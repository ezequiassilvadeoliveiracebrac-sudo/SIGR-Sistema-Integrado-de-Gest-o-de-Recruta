-- Limpeza automática recomendada para ser usada pelo cron já existente.
create or replace function public.sigr_cleanup_communications()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.sigr_operator_sessions where expires_at < now();
  delete from public.sigr_operator_attempts where attempted_at < now() - interval '30 days';
  delete from public.sigr_call_signals where created_at < now() - interval '1 day';
  update public.sigr_calls set status = 'missed', ended_at = now()
    where status = 'ringing' and created_at < now() - interval '5 minutes';
end;
$$;
revoke all on function public.sigr_cleanup_communications() from public, anon, authenticated;
